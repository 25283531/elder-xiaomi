"""老年人常见基础病用药的**品名归类**与「老人这句话指的是哪一味」的匹配。

为什么需要这个模块
----------------
老人不会说药名，他说「我刚才吃过降压药了」「吃了那个降血糖的」。而服务端
手里只有家属填的**药名**（``Reminder.medicines[].name``）。要把这两边对上，
必须有一张「类别 ↔ 通用名」的表，以及一个把口语归到类别的函数。

本模块只做**名称归类**，回答「这句话指的是哪一味」，不回答任何别的：
    * 不涉及剂量（剂量红线在 ``catalog.HIGH_RISK_MEDS`` / ``no_dose_or_adjust``）；
    * 不涉及能不能一起吃、要不要停药（那是医疗建议，``HARD_GUARDRAILS`` 明令禁止）；
    * 不判断老人是否真的吃了（那是确认流程的事）。
上面三条**刻意不在这里重复实现**，也不修改 ``catalog.py`` —— 两份真源必然漂移，
而漂移在这里的后果是「红线被绕过」或「剂量被这里"顺手"回答」。

三条硬约束（改这个文件之前先读）
------------------------------
1. **不许模糊到「猜」**。认不出来就返回空列表，让上层去追问「是氨氯地平
   还是缬沙坦」。按字符串相似度（编辑距离、拼音首字母、"最像的那个"）硬塞
   一个药名的后果是**让老人确认了一味他没吃的药** —— 认错药比不认危险得多：
   不认只是多问一句，认错会写进服药记录、让家属以为已经吃过。
2. **一个类别可能对应多味药**。老人同时吃氨氯地平和缬沙坦时，说「降压药」
   无法区分是哪一味，此时**返回多个**，由上层追问。这里不做"取第一个"。
3. 只列**通用名**，不列商品名。商品名（络活喜、拜新同、格华止…）各地叫法
   不同、还在不断新增，收进来既列不全又会过期；而药盒和处方上印的是通用名。
   ⚠️ 因此老人若只说商品名（「我吃的络活喜」），这里**认不出来**，会走追问
   —— 这是有意的取舍，不是漏配。要支持商品名，得另建一份可维护的别名表，
   而不是往 ``MED_CATEGORIES`` 里掺。

用法
----
    from .med_categories import match_medicine, match_category

    meds = [m["name"] for m in reminder.medicines]      # ["苯磺酸氨氯地平", "二甲双胍"]
    hit = match_medicine("我刚才吃过降压药了", meds)     # ["苯磺酸氨氯地平"]
    if not hit:
        ...  # 追问，而不是猜
"""
