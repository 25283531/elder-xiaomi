# 剥离后允许参与"包含匹配"的最短长度。
# 3 是底线：更短的名字（如"钙"）在任何一句话里都能撞上，匹配上了也没有信息量。
_MIN_LEN: Final = 3


def _norm(text: str) -> str:
    """归一化：去空白、全角转半角、英文小写。"""
    if not text:
        return ""
    out = []
    for ch in text:
        code = ord(ch)
        # 全角 ASCII（！-～）转半角：老人输入法/ASR 输出里全角数字很常见
        if 0xFF01 <= code <= 0xFF5E:
            ch = chr(code - 0xFEE0)
        out.append(ch)
    return "".join(out).replace(" ", "").replace("\u3000", "").casefold()


def _name_variants(name: str) -> list[str]:
    """一个通用名 → 可能的说法（原样 + 去酸根 + 去剂型），长的在前。

    "苯磺酸氨氯地平" → ["苯磺酸氨氯地平", "氨氯地平"]
    "达比加群酯"     → ["达比加群酯", "达比加群"]
    只做**剥前缀/后缀**这一种变换，不做编辑距离之类的近似 —— 见模块头约束 1。
    """
    base = _norm(name)
    if not base:
        return []
    variants: list[str] = [base]
    cur = base
    changed = True
    # 反复剥：既剥前缀也剥后缀，直到剥不动（"苯磺酸氨氯地平片" 要剥两次）
    while changed:
        changed = False
        for pre in _SALT_PREFIXES:
            if cur.startswith(pre) and len(cur) - len(pre) >= _MIN_LEN:
                cur = cur[len(pre):]
                variants.append(cur)
                changed = True
        for suf in _NAME_SUFFIXES:
            if cur.endswith(suf) and len(cur) - len(suf) >= _MIN_LEN:
                cur = cur[: -len(suf)]
                variants.append(cur)
                changed = True
    # 去重、保序、长的在前（长的更具体，先匹配到就少一次误判）
    seen: list[str] = []
    for v in variants:
        if len(v) >= _MIN_LEN and v not in seen:
            seen.append(v)
    return sorted(seen, key=len, reverse=True)


def match_category(text: str) -> str:
    """把老人的一句话归到某个类别，认不出返回**空串**。

    只看"这句话提到了哪一类药"，不判断他吃没吃、吃了几片。
    返回空串是正常结果（"吃了药""我刚才吃过了"），不是错误 ——
    上层据此追问，而不是硬猜一类。
    """
    norm = _norm(text)
    if not norm:
        return ""
    for alias, category in _CATEGORY_ALIASES:
        if alias in norm:
            return category
    return ""


def _in_category(med_name: str, category: str) -> bool:
    """这味药是否属于该类别。

    两侧都按"去酸根/去剂型后的变体"比：类别表里写的是"氨氯地平"，
    而老人日程里写的是"苯磺酸氨氯地平"，两边都得能互相认出来。
    """
    names = MED_CATEGORIES.get(category, ())
    med_variants = _name_variants(med_name)
    for n in names:
        for nv in _name_variants(n):
            for mv in med_variants:
                if nv == mv or nv in mv or mv in nv:
                    return True
    return False


def match_medicine(text: str, medicines: list[str]) -> list[str]:
    """老人说的话 → 这批药里被**点名**的那几味（保持 ``medicines`` 的顺序）。

    优先级（严格按序，前一步命中就不再看后一步）：

      ① **直接说药名**：``medicines`` 里的名字（含去酸根/去前缀后的主名）
         出现在这句话里。这一步最可信 —— 老人自己说出了药名。
      ② **说类别**：走 :func:`match_category` 得到类别，再在这个类别里筛
         ``medicines`` 里命中的。
      ③ 都没命中 → 返回 ``[]``，**由调用方追问**。

    返回空列表时不要自己补一个"最像的"：见模块头约束 1。
    返回多个时也不要自己挑一个：见约束 2（同类别多药，让老人自己说）。

    ⚠️ "防血栓"按产品口径归到 **抗凝药**（见 ``_CATEGORY_ALIASES``）。只吃
    阿司匹林（抗血小板）的老人说"防血栓的药"时，这里会**匹配不到**、返回
    空列表让上层追问 —— 这是有意的：把阿司匹林当成抗凝药确认，比多问一句
    危险得多。若将来要区分，得先让老人能说清是"抗凝"还是"抗血小板"。
    """
    norm = _norm(text)
    if not norm or not medicines:
        return []

    # ① 直接命中药名（含去酸根变体）
    direct = [m for m in medicines if m and any(v in norm for v in _name_variants(m))]
    if direct:
        return direct

    # ② 类别词 → 该类别里命中的药
    category = match_category(text)
    if category:
        return [m for m in medicines if m and _in_category(m, category)]

    # ③ 不猜
    return []
